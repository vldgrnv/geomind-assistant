SYSTEM_PROMPT = "Ты — эксперт по геоинформационным системам (ГИС)."

ANSWER_TEMPLATE = """Ответь на вопрос пользователя, используя ПРИЛОЖЕННЫЙ АЛГОРИТМ и свои знания.

Вопрос пользователя: «{user_query}»

Алгоритм:
{algorithm_text}

Правила ответа:
- Язык ответа: русский.
- Если пользователь просит написать код, скрипт или программу — дай ТОЛЬКО Python-код: для ArcGIS используй arcpy, для QGIS используй PyQGIS. Код должен быть рабочим, с комментариями на русском. Никаких пошаговых инструкций в этом случае.
- Если пользователь НЕ просит код — дай пошаговую инструкцию для ArcMap 10.4–10.8 и QGIS, без лишней теории.
- Оформление: строго Markdown — заголовки через ### (например ### arcpy и ### PyQGIS, или ### ArcMap и ### QGIS), каждый шаг/строка кода с новой строки, между блоками пустая строка. Не сливай всё в один абзац."""


def build_answer_prompt(user_query, algorithm_text):
    return ANSWER_TEMPLATE.format(user_query=user_query, algorithm_text=algorithm_text)
